// Material 3 color tokens from Google's Material Color Utilities. Imported via esbuild by build-ui.mjs
// (the package uses extensionless ESM imports that plain Node cannot resolve).
import { DynamicColor, Hct, MaterialDynamicColors, SchemeVibrant, argbFromHex, customColor, hexFromArgb } from '@material/material-color-utilities';

function kebab(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
}

function schemeTokens(seed, custom, isDark) {
  const scheme = new SchemeVibrant(Hct.fromInt(argbFromHex(seed)), isDark, 0);
  const lines = [];
  for (const [name, value] of Object.entries(MaterialDynamicColors)) {
    if (!(value instanceof DynamicColor) || name.endsWith('PaletteKeyColor')) continue;
    lines.push(`--md-sys-color-${kebab(name)}: ${hexFromArgb(value.getArgb(scheme))};`);
  }
  for (const c of custom) {
    const group = customColor(argbFromHex(seed), { name: c.name, value: argbFromHex(c.hex), blend: true })[isDark ? 'dark' : 'light'];
    lines.push(`--app-color-${c.name}: ${hexFromArgb(group.color)};`);
    lines.push(`--app-color-on-${c.name}: ${hexFromArgb(group.onColor)};`);
    lines.push(`--app-color-${c.name}-container: ${hexFromArgb(group.colorContainer)};`);
    lines.push(`--app-color-on-${c.name}-container: ${hexFromArgb(group.onColorContainer)};`);
  }
  return lines;
}

export function themeCss({ seed, custom }) {
  const light = schemeTokens(seed, custom, false).map((l) => `  ${l}`).join('\n');
  const dark = schemeTokens(seed, custom, true).map((l) => `    ${l}`).join('\n');
  return `/* Generated by scripts/build-ui.mjs from seed ${seed} (Material Color Utilities, vibrant). Do not edit. */
:root {
  color-scheme: light dark;
  --md-ref-typeface-brand: 'Roboto', 'Noto Sans Tamil', 'Noto Sans Devanagari', system-ui, sans-serif;
  --md-ref-typeface-plain: 'Roboto', 'Noto Sans Tamil', 'Noto Sans Devanagari', system-ui, sans-serif;
${light}
}
@media (prefers-color-scheme: dark) {
  :root {
${dark}
  }
}
`;
}
