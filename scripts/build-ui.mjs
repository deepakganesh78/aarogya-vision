async function buildTheme() {
  const tmp = path.join(os.tmpdir(), `av-theme-${process.pid}.mjs`);
  await esbuild.build({ entryPoints: [path.join(root, 'scripts', 'theme-tokens.mjs')], bundle: true, platform: 'node', format: 'esm', outfile: tmp, logLevel: 'silent' });
  try {
    const { themeCss } = await import(pathToFileURL(tmp).href);
    await fs.writeFile(path.join(out, 'theme.css'), themeCss({ seed: SEED, custom: CUSTOM }));
  } finally {
    await fs.rm(tmp, { force: true });
  }
}

async function buildIcons() {
  const dir = path.join(root, 'node_modules', '@material-symbols', 'svg-400', 'rounded');
  const entries = {};
  for (const name of ICONS) {
    for (const [key, file] of [[name, `${name}.svg`], [`${name}:fill`, `${name}-fill.svg`]]) {
      let svg;
      try {
        svg = await fs.readFile(path.join(dir, file), 'utf8');
      } catch {
        if (!key.endsWith(':fill')) throw new Error(`Material Symbol not found: ${name}`);
        continue;
      }
      entries[key] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
    }
  }
  const js = `// Generated by scripts/build-ui.mjs from @material-symbols/svg-400 (rounded). Do not edit.\nexport const ICON_PATHS = ${JSON.stringify(entries)};\n`;
  await fs.writeFile(path.join(out, 'icons.js'), js);
}

async function bundle() {
  await esbuild.build({
    entryPoints: [path.join(root, 'ui', 'material.js')],
    bundle: true,
    format: 'esm',
    minify: true,
    target: ['es2021'],
    legalComments: 'linked',
    outfile: path.join(out, 'material.js'),
    logLevel: 'warning'
  });
  await esbuild.build({
    entryPoints: [path.join(root, 'ui', 'three.js')],
    bundle: true,
    format: 'esm',
    minify: true,
    target: ['es2021'],
    legalComments: 'linked',
    outfile: path.join(out, 'three.js'),
    logLevel: 'warning'
  });
  await esbuild.build({
    entryPoints: [path.join(root, 'ui', 'fonts.css')],
    bundle: true,
    minify: true,
    loader: { '.woff2': 'file', '.woff': 'file' },
    assetNames: 'fonts/[name]',
    outfile: path.join(out, 'fonts.css'),
    logLevel: 'warning'
  });
}

// Google AI Edge MediaPipe LLM Inference (Gemma on the phone), served from our own origin.
// Only the SIMD (non-module) WASM build is copied: every browser with WebGPU also has WASM SIMD.
async function copyGenai() {
  const src = path.join(root, 'node_modules', '@mediapipe', 'tasks-genai');
  const dest = path.join(out, 'genai');
  await fs.mkdir(dest, { recursive: true });
  await Promise.all([
    fs.copyFile(path.join(src, 'genai_bundle.mjs'), path.join(dest, 'genai_bundle.mjs')),
    fs.copyFile(path.join(src, 'wasm', 'genai_wasm_internal.js'), path.join(dest, 'genai_wasm_internal.js')),
    fs.copyFile(path.join(src, 'wasm', 'genai_wasm_internal.wasm'), path.join(dest, 'genai_wasm_internal.wasm'))
  ]);
}

await fs.rm(out, { recursive: true, force: true });
await fs.mkdir(out, { recursive: true });
await Promise.all([bundle(), buildTheme(), buildIcons(), copyGenai()]);
const files = await fs.readdir(out, { recursive: true });
console.log(`built public/vendor (${files.filter((f) => path.extname(f)).length} files)`);
