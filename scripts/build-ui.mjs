// Builds the Material 3 front-end assets into public/vendor/:
//   material.js  official @material/web components (esbuild bundle)
//   theme.css    Material 3 color tokens generated with Google's Material Color Utilities (light + dark)
//   fonts.css    self-hosted Roboto + Noto Sans Tamil/Devanagari (+ fonts/*.woff2)
//   icons.js     Material Symbols (rounded) SVG paths for the icons the app uses
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'public', 'vendor');

// Seed: Google Blue. Semantic warning/success colors are harmonised toward the seed.
const SEED = '#0B57D0';
const CUSTOM = [
  { name: 'warning', hex: '#B26A00' },
  { name: 'success', hex: '#146C2E' }
];

const ICONS = [
  'add', 'arrow_back', 'star_shine', 'chat', 'check_circle', 'child_care', 'close', 'cloud_done', 'cloud_off', 'cloud_upload',
  'delete', 'error', 'fact_check', 'graphic_eq', 'history', 'image', 'inbox', 'info', 'lock', 'logout', 'medical_information',
  'menu_book', 'mic', 'person', 'photo_camera', 'refresh', 'schedule', 'send', 'stethoscope', 'stop', 'sync', 'translate',
  'verified_user', 'warning', 'person_add', 'search', 'pregnant_woman', 'volume_up', 'repeat', 'location_on', 'local_hospital',
  'download', 'groups', 'timer', 'today', 'edit', 'badge', 'stop_circle'
];

async function buildTheme() {
  const tmp = path.join(os.tmpdir(), `av-theme-${process.pid}.mjs`);
  await esbuild.build({ entryPoints: [path.join(root, 'scripts', 'theme-tokens.mjs')], bundle: true, platform: 'node', format: 'esm', outfile: tmp, logLevel: 'silent' });
  try {
    const { themeCss } = await import(pathToFileURL(tmp).href);
    await fs.writeFile(path.join(out, 'theme.css'), themeCss({ seed: SEED, custom: CUSTOM }));
  } finally {
    await fs.rm(tmp, { force: true });
  }
}

async function buildIcons() {
  const dir = path.join(root, 'node_modules', '@material-symbols', 'svg-400', 'rounded');
  const entries = {};
  for (const name of ICONS) {
    for (const [key, file] of [[name, `${name}.svg`], [`${name}:fill`, `${name}-fill.svg`]]) {
      let svg;
      try {
        svg = await fs.readFile(path.join(dir, file), 'utf8');
      } catch {
        if (!key.endsWith(':fill')) throw new Error(`Material Symbol not found: ${name}`);
        continue;
      }
      entries[key] = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
    }
  }
  const js = `// Generated by scripts/build-ui.mjs from @material-symbols/svg-400 (rounded). Do not edit.\nexport const ICON_PATHS = ${JSON.stringify(entries)};\n`;
  await fs.writeFile(path.join(out, 'icons.js'), js);
}

async function bundle() {
  await esbuild.build({
    entryPoints: [path.join(root, 'ui', 'material.js')],
    bundle: true,
    format: 'esm',
    minify: true,
    target: ['es2021'],
    legalComments: 'linked',
    outfile: path.join(out, 'material.js'),
    logLevel: 'warning'
  });
  await esbuild.build({
    entryPoints: [path.join(root, 'ui', 'fonts.css')],
    bundle: true,
    minify: true,
    loader: { '.woff2': 'file', '.woff': 'file' },
    assetNames: 'fonts/[name]',
    outfile: path.join(out, 'fonts.css'),
    logLevel: 'warning'
  });
}

await fs.rm(out, { recursive: true, force: true });
await fs.mkdir(out, { recursive: true });
await Promise.all([bundle(), buildTheme(), buildIcons()]);
const files = await fs.readdir(out, { recursive: true });
console.log(`built public/vendor (${files.filter((f) => path.extname(f)).length} files)`);
